class User {
  final String id;
  final String name;
  final String email;
  final String phone;
  final String role;
  final String department;
  final String avatarInitials;

  const User({
    required this.id,
    required this.name,
    required this.email,
    required this.phone,
    required this.role,
    required this.department,
    required this.avatarInitials,
  });
}
